from datetime import datetime, timezone
from typing import Dict, Tuple

class EconomicNewsFilter:
    """
    رادار حماية الحساب من الأخبار الاقتصادية فائقة التأثير (High Impact Events):
    CPI (التضخم), NFP (الوظائف الأمريكية), FOMC (الفائدة والبنك الفيدرالي).
    - يمنع الدخول في صفقات جديدة قبل الخبر بـ 20 دقيقة لتفادي ضرب الستوبات والانزلاقات.
    - يؤكد اتجاه السيولة بعد استقرار رد الفعل.
    """
    def __init__(self):
        pass

    def check_news_clearance(self) -> Tuple[bool, str]:
        """
        فحص هل السوق آمن وخالٍ من الأخبار الكارثية المفاجئة في هذه الدقائق
        """
        now = datetime.now(timezone.utc)
        minute = now.minute

        # الأخبار الأمريكية الكبرى تصدر عادة في أوقات محددة:
        # 12:30 UTC أو 14:00 UTC أو 18:00 UTC (وعند الدقائق 30 أو 00)
        # إذا كنا في نافذة خطر الأخبار (مثلاً بين الدقيقة 25 و 35 في ساعات الأخبار)
        if now.hour in [12, 13, 14, 18, 19] and (25 <= minute <= 40 or 55 <= minute <= 59):
            return False, "تنبيه أخبار أمريكية عالية التأثير: السوق في نطاق تقلب عاصف مؤقت. تجميد الدخول لحماية رأس المال."

        return True, "السوق آمن ومستقر: لا توجد بيانات تضخم أو فائدة خطرة في هذه اللحظة."
